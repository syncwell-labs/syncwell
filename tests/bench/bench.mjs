// Latency/throughput benchmark: K clients in one room; one publisher updates a
// key at a fixed rate; every other client measures end-to-end sync latency
// (publish → receive) in the same process, so timestamps are directly
// comparable. Reports p50/p95/p99, throughput, and server RSS.
//
// Run: make bench   (env: CLIENTS, DURATION_MS, INTERVAL_MS)
import { spawn } from "node:child_process";
import { setTimeout as sleep } from "node:timers/promises";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Syncwell } from "../../clients/javascript/syncwell.js";
import { waitHealthy } from "../helpers.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BIN = path.join(__dirname, "..", "..", "bin", "syncwell");
const PORT = 8126;
const BASE = `ws://localhost:${PORT}/ws`;

const K = Number(process.env.CLIENTS || 50);
const DURATION_MS = Number(process.env.DURATION_MS || 3000);
const INTERVAL_MS = Number(process.env.INTERVAL_MS || 5);

function percentile(sorted, p) {
  if (!sorted.length) return NaN;
  const idx = Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length));
  return sorted[idx];
}

async function serverRSSkb(pid) {
  try {
    const status = await readFile(`/proc/${pid}/status`, "utf8");
    const m = status.match(/VmRSS:\s+(\d+)\s+kB/);
    return m ? Number(m[1]) : NaN;
  } catch {
    return NaN;
  }
}

async function main() {
  const srv = spawn(BIN, ["-addr", `127.0.0.1:${PORT}`], { stdio: "ignore" });
  try {
    await waitHealthy(PORT);

    // Connect K clients to one room.
    const clients = [];
    for (let i = 0; i < K; i++) clients.push(new Syncwell(BASE, "bench", { clientId: `c${i}` }));
    clients.forEach((c) => c.connect());
    await sleep(500);

    const samples = [];
    const lastSeen = new Array(K).fill(-1);
    for (let i = 1; i < K; i++) {
      clients[i].on("change", (live) => {
        const v = live.lat;
        if (typeof v === "number" && v !== lastSeen[i]) {
          lastSeen[i] = v;
          samples.push(performance.now() - v);
        }
      });
    }

    const pub = clients[0];

    // Warmup (not measured).
    for (let t = 0; t < 20; t++) {
      pub.set("lat", performance.now());
      await sleep(INTERVAL_MS);
    }
    await sleep(200);
    samples.length = 0;

    // Measured run.
    let published = 0;
    const end = performance.now() + DURATION_MS;
    while (performance.now() < end) {
      pub.set("lat", performance.now());
      published++;
      await sleep(INTERVAL_MS);
    }
    await sleep(400); // let stragglers arrive

    const rssKb = await serverRSSkb(srv.pid);
    clients.forEach((c) => c.close());

    samples.sort((a, b) => a - b);
    const fanoutPerPublish = K - 1;
    const throughput = Math.round((samples.length / (DURATION_MS / 1000)));

    const f = (x) => (Number.isNaN(x) ? "n/a" : x.toFixed(2));
    const rows = [
      `| metric | value |`,
      `| --- | --- |`,
      `| concurrent clients | ${K} |`,
      `| publishes | ${published} @ ${1000 / INTERVAL_MS}/s |`,
      `| delivered samples | ${samples.length} (fan-out ×${fanoutPerPublish}) |`,
      `| sync latency p50 | ${f(percentile(samples, 50))} ms |`,
      `| sync latency p95 | ${f(percentile(samples, 95))} ms |`,
      `| sync latency p99 | ${f(percentile(samples, 99))} ms |`,
      `| max latency | ${f(samples[samples.length - 1])} ms |`,
      `| delivery throughput | ${throughput.toLocaleString()} msg/s |`,
      `| server RSS | ${Number.isNaN(rssKb) ? "n/a" : (rssKb / 1024).toFixed(1) + " MB"} |`,
    ];
    const table = rows.join("\n");
    console.log("\n" + table + "\n");

    const doc = `# Syncwell Benchmarks

Generated by \`make bench\` (tests/bench/bench.mjs). Single machine, server + clients in
one box, so these measure engine + loopback, not WAN. Reproduce with:

\`\`\`
CLIENTS=${K} DURATION_MS=${DURATION_MS} INTERVAL_MS=${INTERVAL_MS} make bench
\`\`\`

${table}

**Method:** ${K} websocket clients join one room. One publisher updates a key
every ${INTERVAL_MS} ms; the other ${fanoutPerPublish} clients timestamp each
received update against its publish time (same process clock). Latency is the
publish→receive delta; throughput is delivered messages/second.
`;
    await writeFile(path.join(__dirname, "..", "..", "docs", "product", "BENCHMARKS.md"), doc);
    console.log("wrote docs/product/BENCHMARKS.md");
  } finally {
    srv.kill("SIGKILL");
  }
}

main();
